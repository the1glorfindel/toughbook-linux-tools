def devices(cards, proc=Path('/proc/asound')):
    found = []
    for card in cards:
        props = card.get('properties', {})
        index = props.get('api.alsa.card', props.get('alsa.card'))
        if index is None or not str(index).isdigit():
            continue
        for codec in (proc / f'card{index}').glob('codec#*'):
            content = codec.read_text()
            if 'Codec: Realtek ALC269VC\n' in content and 'Vendor Id: 0x10ec0269' in content:
                found.append({'name': card['name'], 'index': int(index),
                              'profile': card['active_profile'], 'card_serial': card['index'],
                              'codec': '10ec0269:ALC269VC'})
                break
    return found


def cards():
    return devices(json.loads(run('pactl', '--format=json', 'list', 'cards').stdout))


def sink_for(device):
    sinks = json.loads(run('pactl', '--format=json', 'list', 'sinks').stdout)
    found = [s for s in sinks if str(s.get('card')) == str(device['card_serial'])
             and 'analog-stereo' in s['name']]
    if len(found) != 1:
        raise ToolError('Select the Analog Stereo output profile in desktop Sound settings, then retry.')
    return found[0]


def wireplumber_mode():
    version = run('wireplumber', '--version').stdout
    match = re.search(r'\b(\d+)\.(\d+)(?:\.\d+)?\b', version)
    if not match:
        raise ToolError('Could not identify the WirePlumber version.')
    major, minor = map(int, match.groups())
    if (major, minor) == (0, 4):
        return 'legacy'
    if (major, minor) >= (0, 5):
        return 'modern'
    raise ToolError('This WirePlumber version is not supported by the speaker repair.')


def audio_paths(config, mode='modern'):
    rule = ('wireplumber/main.lua.d/51-cf19-speaker.lua' if mode == 'legacy'
            else 'wireplumber/wireplumber.conf.d/51-cf19-speaker.conf')
    return [config / 'alsa-card-profile/paths/cf19-output-speaker.conf',
            config / 'alsa-card-profile/profile-sets/cf19.conf',
            config / rule]


def build_files(config, device_name, system=Path('/usr/share/alsa-card-profile/mixer'), mode='modern'):
    speaker = (system / 'paths/analog-output-speaker.conf').read_text()
    speaker, count = re.subn(r'(\[Element Headphone\]\s*\n)switch = off\s*\nvolume = off',
                            r'\1switch = mute\nvolume = merge', speaker)
    if count != 1:
        raise ToolError('Unexpected speaker profile; no profile changes made.')
    speaker = speaker.replace('.include analog-output.conf.common',
                              f'.include {system}/paths/analog-output.conf.common')
    profile = (system / 'profile-sets/default.conf').read_text()
    if 'analog-output-speaker' not in profile:
        raise ToolError('The default profile has no standard speaker route.')
    profile = profile.replace('analog-output-speaker', 'cf19-output-speaker')
    profile = profile.replace('.include 9999-custom.conf',
                              f'.include {system}/profile-sets/9999-custom.conf')
    rule = '''# Generated by Toughbook Tools (MIT); target this internal card only.
monitor.alsa.rules = [
  {
    matches = [ { device.name = %s } ]
    actions = { update-props = { device.profile-set = "cf19.conf" } }
  }
]
''' % json.dumps(device_name)
    if mode == 'legacy':
        rule = '''-- Generated by Toughbook Tools (MIT); target this internal card only.
table.insert(alsa_monitor.rules, {
  matches = { { { "device.name", "equals", %s } } },
  apply_properties = { ["device.profile-set"] = "cf19.conf" },
})
''' % json.dumps(device_name)
    return dict(zip(audio_paths(config, mode), (speaker, profile, rule)))


def same_device(saved):
    device = choose(cards(), 'name', saved['name'])
    if device['codec'] != saved['codec']:
        raise ToolError('The saved backup belongs to different audio hardware.')
    return device


def restart(device):
    run('systemctl', '--user', 'restart', 'wireplumber')
    deadline = time.monotonic() + 8
    while time.monotonic() < deadline:
        try:
            current = same_device(device)
            run('pactl', 'set-card-profile', current['name'], device['profile'])
            return current, sink_for(current)
        except ToolError:
            time.sleep(.2)
    raise ToolError('WirePlumber did not recreate the analog output. Inspect its user journal.')


def restore_routing(data, sink):
    saved = data['sink']
    if saved.get('active_port'):
        run('pactl', 'set-sink-port', sink['name'], saved['active_port'])
    run('pactl', 'set-sink-volume', sink['name'],
        *[str(v['value']) for v in saved['volume'].values()])
    run('pactl', 'set-sink-mute', sink['name'], '1' if saved['mute'] else '0')
    run('pactl', 'set-default-sink', data['default_sink'])


def restore_backup(path, remove_marker=True, log_fn=None):
    data = load_json(path, 'audio')
    config = config_dir()
    if data['config'] != str(config):
        raise ToolError('Restore this backup as its original user, with the same XDG_CONFIG_HOME.')
    current = None
    saved = set(data['files'])
    allowed = next((audio_paths(config, mode) for mode in ('modern', 'legacy')
                    if saved == {str(path) for path in audio_paths(config, mode)}), None)
    if allowed is None:
        raise ToolError('Backup paths do not match a supported audio configuration.')
    restore_files(data['files'], allowed)
    failures = []
    try:
        current, sink = restart(data['device'])
        restore_routing(data, sink)
    except Exception as exc:
        failures.append(str(exc))
    # Attempt hardware restoration even when session-manager restoration failed.
    try:
        mixer = Path(path).with_suffix('.alsa-state')
        if not mixer.is_file():
            raise ToolError(f'Mixer backup is missing: {mixer}')
        current = current or same_device(data['device'])
        run('alsactl', '-f', mixer, 'restore', str(current['index']))
    except Exception as exc:
        failures.append(str(exc))
    if failures:
        raise ToolError('Configuration restored, but recovery needs attention: ' + '; '.join(failures))
    data['status'] = 'restored'
    save_json(path, data)
    marker = state_dir() / 'audio-installed.json'
    if remove_marker and marker.exists() and load_json(marker).get('baseline') == str(Path(path).resolve()):
        marker.unlink()
    message = 'Previous audio configuration and mixer state restored.'
    if log_fn:
        log_fn(message)
    else:
        print(message)


def playback(sink):
    for sample in ('Front_Left', 'Front_Right'):
        run('pw-play', '--target', sink['name'],
            runtime.data_file(f'sounds/alsa/{sample}.wav', f'/usr/share/sounds/alsa/{sample}.wav'), timeout=12)


def set_route(sink, port):
    run('pactl', 'set-sink-port', sink['name'], port)
    run('pactl', 'set-sink-mute', sink['name'], '0')
    run('pactl', 'set-sink-volume', sink['name'], '60%')


def repair(device, confirm_fn=None, start_fn=None, cancel_event=None, log_fn=None):
    """Run the reversible repair, optionally using GUI prompts and cancellation.

    The default callbacks retain the original interactive CLI behavior. GUI
    callers can supply a confirmation callback that marshals prompts to its
    main thread, plus a threading.Event to request rollback.
    """
    confirm_fn = confirm_fn or confirm
    gui_start = start_fn is not None
    start_fn = start_fn or input

    def log(message):
        if log_fn:
            log_fn(message)
        else:
            print(message, flush=True)

    def check_cancelled():
        if cancel_event is not None and cancel_event.is_set():
            raise ToolError('Audio repair cancelled; restoring the previous configuration.')

    config = config_dir()
    files = build_files(config, device['name'], mode=wireplumber_mode())  # Validate before changing anything.
    sink = sink_for(device)
    marker = state_dir() / 'audio-installed.json'
    existing = load_json(marker, 'audio-installation') if marker.exists() else None
    if existing:
        baseline = Path(existing['baseline'])
        original = load_json(baseline, 'audio')
        if original['device']['name'] != device['name'] or original['config'] != str(config):
            raise ToolError('An installation for another device/configuration exists; restore it first.')
        if set(original['files']) != {str(path) for path in files}:
            raise ToolError('WirePlumber configuration format changed; restore the original audio backup before repairing again.')
    else:
        baseline = None
    path = backup_path('audio')
    mixer = path.with_suffix('.alsa-state')
    run('alsactl', '-f', mixer, 'store', str(device['index']))
    mixer.chmod(0o600)
    data = {'kind': 'audio', 'device': device, 'config': str(config),
            'files': snapshot(files), 'sink': {key: sink[key] for key in ('active_port', 'volume', 'mute')},
            'default_sink': run('pactl', 'get-default-sink').stdout.strip(), 'status': 'testing'}
    save_json(path, data)
    accepted = False
    log(f'Backup: {path}')
    try:
        check_cancelled()
        start_message = 'Unplug wired headphones, then press Enter to test the internal speaker. '
        if gui_start:
            accepted_start = start_fn('Unplug wired headphones, then continue to test the internal speaker?')
        else:
            start_fn(start_message)
            accepted_start = True
        if not accepted_start:
            raise ToolError('Audio repair cancelled; restoring the previous configuration.')
        check_cancelled()
        ports = {p['name'] for p in sink['ports']}
        port = 'cf19-output-speaker' if 'cf19-output-speaker' in ports else 'analog-output-speaker'
        set_route(sink, port)
        run('amixer', '-c', str(device['index']), 'sset', 'Auto-Mute Mode', 'Disabled')
        run('amixer', '-c', str(device['index']), 'sset', 'Headphone', '80%', 'unmute')
        playback(sink)
        if not confirm_fn('Did you hear the INTERNAL speaker?'):
            log('No fix saved. Test wired headphones next to help isolate hardware/routing.')
            return 2
        check_cancelled()
        for target, content in files.items():
            target.parent.mkdir(parents=True, exist_ok=True)
            temporary = target.with_suffix(target.suffix + '.tmp')
            temporary.write_text(content)
            temporary.replace(target)
        _, sink = restart(device)
        check_cancelled()
        set_route(sink, 'cf19-output-speaker')
        run('pactl', 'set-default-sink', sink['name'])
        playback(sink)
        if not confirm_fn('Does the internal speaker STILL work after the audio service restart?'):
            return 2
        check_cancelled()
        data['status'] = 'accepted'
        save_json(path, data)
        baseline = baseline or path
        save_json(marker, {'kind': 'audio-installation', 'baseline': str(baseline.resolve()),
                           'latest': str(path.resolve())})
        accepted = True
        log('Speaker fix saved. Test normal volume/mute controls and a logout/login or reboot.')
        script = Path(__file__).resolve().parent.parent / 'fix-audio.py'
        log('To uninstall: ' + shlex.join(runtime.command('fix-audio.py', '--restore', baseline)))
        return 0
    finally:
        if not accepted:
            restore_backup(path, remove_marker=False, log_fn=log_fn)


def main(argv=None):
    parser = argparse.ArgumentParser(description='Repair the CF-19 ALC269VC internal speaker on PipeWire desktops.')
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--status', action='store_true', help='List eligible audio devices and installed baseline; no changes')
    group.add_argument('--restore', metavar='BACKUP', help='Restore a saved configuration and mixer state')
    parser.add_argument('--device', help='Eligible card name from --status')
    args = parser.parse_args(argv)
    desktop_user()
    check_model()
    require('pactl', 'pw-play', 'amixer', 'alsactl', 'systemctl')
    if args.status:
        marker = state_dir(create=False) / 'audio-installed.json'
        print(json.dumps({'devices': cards(), 'installation': load_json(marker) if marker.exists() else None}, indent=2))
        return 0
    if args.restore:
        restore_backup(args.restore)
        return 0
    if not os.isatty(0):
        raise ToolError('Run interactively in a desktop terminal so you can confirm playback.')
    device = choose(cards(), 'name', args.device)
    def interrupted(signum, frame):
        raise KeyboardInterrupt

    previous = signal.signal(signal.SIGTERM, interrupted)
    try:
        return repair(device)
    finally:
        signal.signal(signal.SIGTERM, previous)
